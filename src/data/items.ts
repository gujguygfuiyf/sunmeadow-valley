export const ALL_SEED_IDS = [
  'seed_parsnip',
  'seed_tulip',
  'seed_strawberry',
  'seed_blueberry',
  'seed_melon',
  'seed_pumpkin',
  'seed_cranberry',
  'seed_snow_yam',
] as const;

export const SHOP_SEED_IDS = ALL_SEED_IDS;

export function getItemDef(itemId: string): ItemDefinition | undefined {
  return ITEM_CATALOG[itemId];
}

export function getSeedsForSeason(season: SeasonId, includeAll = false): ItemDefinition[] {
  const result: ItemDefinition[] = [];
  for (const id of ALL_SEED_IDS) {
    const def = ITEM_CATALOG[id];
    if (!def) continue;
    if (includeAll || !def.seasons || def.seasons.includes(season)) {
      result.push(def);
    }
  }
  return result;
}
